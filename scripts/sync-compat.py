#!/usr/bin/env python3
"""Generate the Codex CLI and OpenCode discovery files from ai-harness/.

ai-harness/ is the source of truth. Run this after changing a skill, agent or
command there, and commit the result:

    python3 scripts/sync-compat.py          # regenerate
    python3 scripts/sync-compat.py --check  # exit 1 if anything is stale

What it writes:
- .agents/skills/<name> -> symlink to each ai-harness skill (and web3 add-on
  skill), named after the skill's `name` field. Codex and OpenCode both read
  .agents/skills/, so there is no .opencode/skills/.
- .opencode/agents/<name>.md: each ai-harness agent with OpenCode frontmatter.
  The Claude `tools` list becomes a `permission` map; the body is unchanged.
- .opencode/commands/<name>.md: each ai-harness command that works outside
  Claude Code, with Claude-only frontmatter dropped and plugin paths rewritten.

Standard library only.
"""
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HARNESS = os.path.join(ROOT, "ai-harness")
SKILL_DIRS = [os.path.join(HARNESS, "skills"), os.path.join(HARNESS, "web3", "skills")]
AGENTS_SRC = os.path.join(HARNESS, "agents")
COMMANDS_SRC = os.path.join(HARNESS, "commands")

SKILLS_OUT = os.path.join(ROOT, ".agents", "skills")
AGENTS_OUT = os.path.join(ROOT, ".opencode", "agents")
COMMANDS_OUT = os.path.join(ROOT, ".opencode", "commands")

# loop-status reads Claude Code transcripts under ~/.claude/projects, which
# OpenCode does not write.
SKIP_COMMANDS = {"loop-status"}

# Where the OpenCode leak-check command finds the scanner. Users can override
# it with ZSKILLS_AI_HARNESS; the default matches the README's clone layout.
PLUGIN_ROOT = "${ZSKILLS_AI_HARNESS:-./zSkills/ai-harness}"

NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
GENERATED = "<!-- Generated by scripts/sync-compat.py from {src}. Edit the source, then re-run it. -->\n"


def split_frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        raise ValueError("no frontmatter")
    fields = {}
    for line in m.group(1).splitlines():
        km = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if km:
            fields[km.group(1)] = km.group(2).strip()
    return fields, m.group(2)


def unquote(v):
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    return v


def yaml_str(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def skill_links():
    links = {}
    for base in SKILL_DIRS:
        for d in sorted(os.listdir(base)):
            path = os.path.join(base, d, "SKILL.md")
            if not os.path.isfile(path):
                continue
            name = unquote(split_frontmatter(read(path))[0].get("name", ""))
            if not NAME_RE.match(name) or len(name) > 64:
                sys.exit(f"sync-compat: bad skill name {name!r} in {path}")
            if name in links:
                sys.exit(f"sync-compat: duplicate skill name {name!r} in {path}")
            links[name] = os.path.relpath(os.path.join(base, d), SKILLS_OUT)
    return links


def opencode_agent(src_name):
    fields, body = split_frontmatter(read(os.path.join(AGENTS_SRC, src_name)))
    tools = {t.strip() for t in fields.get("tools", "").split(",") if t.strip()}
    can_edit = bool(tools & {"Write", "Edit", "MultiEdit"})
    can_bash = "Bash" in tools
    # A Claude subagent can only use the tools it lists; mirror that. MCP tools
    # (docs-lookup's Context7) keep OpenCode's default.
    fm = [
        "---",
        f"description: {yaml_str(unquote(fields['description']))}",
        "mode: subagent",
        "permission:",
        f"  edit: {'allow' if can_edit else 'deny'}",
        f"  bash: {'allow' if can_bash else 'deny'}",
        f"  webfetch: {'allow' if 'WebFetch' in tools else 'deny'}",
        f"  websearch: {'allow' if 'WebSearch' in tools else 'deny'}",
        "  task: deny",
        "---",
    ]
    return "\n".join(fm) + "\n" + GENERATED.format(src=f"ai-harness/agents/{src_name}") + body


def opencode_command(src_name):
    fields, body = split_frontmatter(read(os.path.join(COMMANDS_SRC, src_name)))
    body = body.replace("${ARGUMENTS:-.}", "$ARGUMENTS")  # precommit.py defaults to .
    body = body.replace("${CLAUDE_PLUGIN_ROOT}", PLUGIN_ROOT)
    if "CLAUDE_PLUGIN_ROOT" in body:
        sys.exit(f"sync-compat: unhandled CLAUDE_PLUGIN_ROOT in {src_name}")
    fm = ["---", f"description: {yaml_str(unquote(fields['description']))}", "---"]
    return "\n".join(fm) + "\n" + GENERATED.format(src=f"ai-harness/commands/{src_name}") + body


def wanted_files():
    files = {}
    for f in sorted(os.listdir(AGENTS_SRC)):
        if f.endswith(".md"):
            files[os.path.join(AGENTS_OUT, f)] = opencode_agent(f)
    for f in sorted(os.listdir(COMMANDS_SRC)):
        if f.endswith(".md") and f[:-3] not in SKIP_COMMANDS:
            files[os.path.join(COMMANDS_OUT, f)] = opencode_command(f)
    return files


def main():
    check = "--check" in sys.argv[1:]
    links = skill_links()
    files = wanted_files()
    stale = []

    # Skill symlinks
    existing = set(os.listdir(SKILLS_OUT)) if os.path.isdir(SKILLS_OUT) else set()
    for extra in sorted(existing - set(links)):
        stale.append(f".agents/skills/{extra} (remove)")
        if not check:
            p = os.path.join(SKILLS_OUT, extra)
            os.unlink(p) if os.path.islink(p) or os.path.isfile(p) else shutil.rmtree(p)
    for name, target in links.items():
        p = os.path.join(SKILLS_OUT, name)
        if os.path.islink(p) and os.readlink(p) == target:
            continue
        stale.append(f".agents/skills/{name}")
        if not check:
            os.makedirs(SKILLS_OUT, exist_ok=True)
            if os.path.lexists(p):
                os.unlink(p)
            os.symlink(target, p)

    # Generated agent and command files
    for out_dir in (AGENTS_OUT, COMMANDS_OUT):
        if os.path.isdir(out_dir):
            for f in sorted(os.listdir(out_dir)):
                p = os.path.join(out_dir, f)
                if p not in files:
                    stale.append(os.path.relpath(p, ROOT) + " (remove)")
                    if not check:
                        os.unlink(p)
    for p, content in files.items():
        if os.path.isfile(p) and read(p) == content:
            continue
        stale.append(os.path.relpath(p, ROOT))
        if not check:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8") as f:
                f.write(content)

    if check:
        if stale:
            print("sync-compat: stale, run python3 scripts/sync-compat.py:")
            for s in stale:
                print("  " + s)
            sys.exit(1)
        print("sync-compat: up to date")
    else:
        print(f"sync-compat: {len(stale)} change(s)" + "".join("\n  " + s for s in stale))


if __name__ == "__main__":
    main()
